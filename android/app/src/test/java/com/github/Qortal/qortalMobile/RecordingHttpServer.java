package com.github.Qortal.qortalMobile;

import java.io.ByteArrayOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.OutputStream;
import java.net.InetAddress;
import java.net.InetSocketAddress;
import java.net.Proxy;
import java.net.ProxySelector;
import java.net.ServerSocket;
import java.net.Socket;
import java.net.SocketAddress;
import java.net.URI;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.Collections;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.TreeMap;
import java.util.concurrent.CopyOnWriteArrayList;

/**
 * A tiny HTTP/1.1 server on 127.0.0.1 that records every request it gets. It
 * stands in for a node, or for a carrier's HTTP proxy: a proxy is a server
 * that gets the whole URL in the request line ("GET http://host:port/path").
 * One request per connection, so no client reuses a connection between
 * checks. Plain java.net, like the other unit tests' stand-ins.
 */
final class RecordingHttpServer implements AutoCloseable {
    /** One reply. */
    static final class Reply {
        final int status;
        final String body;
        final List<String[]> headers = new ArrayList<>();

        Reply(int status, String type, String body) {
            this.status = status;
            this.body = body;
            if (type != null) header("Content-Type", type);
        }

        Reply header(String name, String value) {
            headers.add(new String[] {name, value});
            return this;
        }
    }

    interface Responder {
        /** {@code target} is the request line's target, as sent. */
        Reply answer(String target, Map<String, String> headers);
    }

    /** One request as it arrived. */
    static final class Request {
        final String line;
        final String target;
        final Map<String, String> headers;

        Request(String line, String target, Map<String, String> headers) {
            this.line = line;
            this.target = target;
            this.headers = headers;
        }
    }

    final List<Request> requests = new CopyOnWriteArrayList<>();
    private final ServerSocket socket;
    private final Responder responder;

    RecordingHttpServer(Responder responder) throws IOException {
        this.responder = responder;
        socket = new ServerSocket(0, 50, InetAddress.getLoopbackAddress());
        Thread acceptor = new Thread(() -> {
            while (!socket.isClosed()) {
                try {
                    Socket client = socket.accept();
                    Thread worker = new Thread(() -> serve(client));
                    worker.setDaemon(true);
                    worker.start();
                } catch (IOException e) {
                    return;
                }
            }
        });
        acceptor.setDaemon(true);
        acceptor.start();
    }

    int port() {
        return socket.getLocalPort();
    }

    /** The request targets, in order. */
    List<String> targets() {
        List<String> out = new ArrayList<>();
        for (Request r : requests) out.add(r.target);
        return out;
    }

    @Override
    public void close() throws IOException {
        socket.close();
    }

    /**
     * What a carrier's squid sends back when it cannot reach the address it
     * was asked for (as seen on the owner's phone for 127.0.0.1).
     */
    static Reply squidRefusal(String target) {
        return new Reply(
            503,
            "text/html;charset=utf-8",
            "<html><body><h1>ERROR</h1><p>The requested URL could not be retrieved</p><p>"
                + target
                + "</p><p>Connection to 127.0.0.1 failed. (111) Connection refused</p>"
                + "<p>Generated by mproxy (squid/4.10)</p></body></html>"
        );
    }

    /**
     * A selector like Android's own when the network has an HTTP proxy (an
     * APN proxy on mobile data) and an empty exclusion list: every http(s)
     * address, loopback included, goes to {@code proxyPort}. The JVM's own
     * default selector exempts loopback (http.nonProxyHosts defaults to
     * "localhost|127.*|[::1]|..."), so setting http.proxyHost alone would not
     * show the phone's bug here.
     */
    static ProxySelector androidLikeSelector(int proxyPort) {
        final Proxy proxy = new Proxy(Proxy.Type.HTTP, new InetSocketAddress(InetAddress.getLoopbackAddress(), proxyPort));
        return new ProxySelector() {
            @Override
            public List<Proxy> select(URI uri) {
                String scheme = uri.getScheme() == null ? "" : uri.getScheme().toLowerCase(Locale.ROOT);
                if ("http".equals(scheme) || "https".equals(scheme)) {
                    return Collections.singletonList(proxy);
                }
                return Collections.singletonList(Proxy.NO_PROXY);
            }

            @Override
            public void connectFailed(URI uri, SocketAddress address, IOException e) {}
        };
    }

    private void serve(Socket client) {
        try (Socket s = client) {
            InputStream in = s.getInputStream();
            ByteArrayOutputStream head = new ByteArrayOutputStream();
            int b;
            while ((b = in.read()) != -1) {
                head.write(b);
                byte[] sofar = head.toByteArray();
                int n = sofar.length;
                if (n >= 4 && sofar[n - 4] == '\r' && sofar[n - 3] == '\n' && sofar[n - 2] == '\r' && sofar[n - 1] == '\n') break;
            }
            String[] lines = new String(head.toByteArray(), StandardCharsets.ISO_8859_1).split("\r\n");
            String[] requestLine = lines[0].split(" ");
            String target = requestLine.length > 1 ? requestLine[1] : "";
            Map<String, String> headers = new TreeMap<>(String.CASE_INSENSITIVE_ORDER);
            for (int i = 1; i < lines.length; i++) {
                int colon = lines[i].indexOf(':');
                if (colon <= 0) continue;
                headers.put(lines[i].substring(0, colon), lines[i].substring(colon + 1).trim());
            }
            requests.add(new Request(lines[0], target, headers));
            Reply reply = responder.answer(target, headers);
            byte[] body = reply.body.getBytes(StandardCharsets.UTF_8);
            StringBuilder out = new StringBuilder("HTTP/1.1 " + reply.status + " Status\r\n");
            for (String[] h : reply.headers) out.append(h[0]).append(": ").append(h[1]).append("\r\n");
            out.append("Content-Length: ").append(body.length).append("\r\n");
            out.append("Connection: close\r\n\r\n");
            OutputStream os = s.getOutputStream();
            os.write(out.toString().getBytes(StandardCharsets.UTF_8));
            os.write(body);
            os.flush();
        } catch (IOException | RuntimeException e) {
            // The client went away or sent nonsense.
        }
    }
}
